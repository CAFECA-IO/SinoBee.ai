/**
 * Generate prisma/sqlite/schema.prisma from the PostgreSQL schema (prisma/schema.prisma).
 * Run after every schema change:  npm run db:sqlite-schema
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
let s = readFileSync(path.join(root, "prisma/schema.prisma"), "utf8");
s = s
  .replace(/provider\s*=\s*"postgresql"/, 'provider = "sqlite"')
  .replace(/output\s*=\s*"\.\.\/src\/generated\/prisma"/, 'output   = "../../src/generated/sqlite"')
  .replace(/\s@db\.\w+(\([^)]*\))?/g, "");
s = "// GENERATED by scripts/sqlite-schema.ts from prisma/schema.prisma — do not edit.\n\n" + s;
mkdirSync(path.join(root, "prisma/sqlite"), { recursive: true });
writeFileSync(path.join(root, "prisma/sqlite/schema.prisma"), s);
console.log("wrote prisma/sqlite/schema.prisma");
