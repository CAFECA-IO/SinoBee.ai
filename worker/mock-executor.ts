import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import * as tar from "tar";
import { modelCatalog } from "../src/lib/models";
import { tokenCostUsd } from "../src/lib/pricing";
import { referenceNotes } from "../src/lib/crowd/agent";
import type { Executor, RunContext, RunResult, TaskWithRefs, Usage } from "./types";

/**
 * Development executor (RUNNER_MODE=mock): simulates a SinoBee run without Docker or model keys.
 * Usage grows ~every second so the budget / top-up flow can be exercised end to end.
 * Everything it produces is clearly labelled as simulated.
 */
const progress = new Map<string, Usage>();

export class MockExecutor implements Executor {
  async run(task: TaskWithRefs, ctx: RunContext): Promise<RunResult> {
    const steps = Number(process.env.MOCK_STEPS ?? 8);
    const perStepIn = Number(process.env.MOCK_INPUT_TOKENS_PER_STEP ?? 40_000);
    const perStepOut = Number(process.env.MOCK_OUTPUT_TOKENS_PER_STEP ?? 4_000);
    const m = (await modelCatalog()).get(task.model)?.usd;
    const usage: Usage = progress.get(task.id) ?? { inputTokens: Number(task.inputTokens), outputTokens: Number(task.outputTokens), cacheReadTokens: Number(task.cacheReadTokens), cacheWriteTokens: Number(task.cacheWriteTokens), tokenCostUsd: Number(task.tokenCostUsd) };
    const start = Date.now();
    await ctx.log(`[mock runner] ${ctx.continuation ? "continuing" : "starting"} simulated run on ${task.model}`);
    if (task.crowdfund) {
      const notes = await referenceNotes(task.id);
      await ctx.log(`[mock runner] read inputs/backer-notes.md (${notes.count} reference note(s))${task.reworkNotes ? "; reworking with the backers' feedback" : ""}`);
    }
    let stopped = false;
    for (let i = 0; i < steps; i++) {
      await new Promise((r) => setTimeout(r, Number(process.env.MOCK_STEP_MS ?? 1000)));
      usage.inputTokens += perStepIn;
      usage.outputTokens += perStepOut;
      // pretend half of every new prompt after the first step was a cache hit
      if (i > 0) usage.cacheReadTokens = (usage.cacheReadTokens ?? 0) + perStepIn / 2;
      usage.tokenCostUsd = tokenCostUsd(m, usage);
      progress.set(task.id, usage);
      await ctx.log(`[mock runner] step ${i + 1}/${steps}`);
      if (task.crowdfund && ctx.progress && (i + 1 === Math.ceil(steps / 2) || i + 1 === steps)) {
        await ctx.progress({ done: i + 1 === steps ? 3 : 1, total: 3, current: "[mock] simulated milestone", note: "simulated progress (mock runner)" });
      }
      if ((await ctx.onUsage({ ...usage }, Math.round((Date.now() - start) / 1000))) === "stop") {
        stopped = true;
        await ctx.log("[mock runner] budget exhausted — stopping");
        break;
      }
    }
    const elapsedSeconds = Math.max(1, Math.round((Date.now() - start) / 1000));
    const summary = `# ${task.title}\n\n> Simulated result produced by the development mock runner (RUNNER_MODE=mock).\n\n${stopped ? "The run stopped early because the budget was exhausted. Partial results are included." : "The simulated run completed."}\n`;

    let acceptance: unknown;
    if (task.crowdfund && !stopped) {
      const criteria = (task.spec as { acceptance?: string[] } | null)?.acceptance ?? [];
      acceptance = { criteria: criteria.map((c) => ({ criterion: c, passed: true, evidence: "simulated (mock runner)" })), summary: "Simulated self-check (mock runner)." };
    }
    let evaluation: unknown;
    if (task.kind === "EVALUATION" && !stopped) {
      const seed = [...task.id].reduce((a, ch) => a + ch.charCodeAt(0), 0);
      const score = 55 + (seed % 40);
      evaluation = {
        score,
        verdict: "Simulated evaluation (mock runner) — not a real measurement",
        summary: "This report was generated by the mock runner for development.",
        metrics: { accuracy: score, robustness: Math.max(0, score - 7), efficiency: Math.min(100, score + 5) },
        cases: [
          { name: "case-1", passed: true, score: score + 3 > 100 ? 100 : score + 3, notes: "simulated" },
          { name: "case-2", passed: score > 70, score: score - 5, notes: "simulated" },
        ],
        process: "1. Prepared the environment (simulated)\n2. Ran the test cases (simulated)\n3. Scored the results (simulated)",
      };
    }

    const tmp = await mkdtemp(path.join(tmpdir(), "sb-mock-"));
    try {
      const out = path.join(tmp, "outputs");
      await mkdir(out, { recursive: true });
      await writeFile(path.join(out, "SUMMARY.md"), summary);
      await writeFile(path.join(out, "result.md"), `Task prompt:\n\n${task.prompt}\n`);
      if (evaluation) await writeFile(path.join(out, "evaluation.json"), JSON.stringify(evaluation, null, 2));
      const file = path.join(tmp, "out.tar.gz");
      await tar.c({ gzip: true, cwd: tmp, file, portable: true }, ["outputs"]);
      const archive = await readFile(file);
      if (!stopped) progress.delete(task.id);
      return { outcome: stopped ? "stopped" : "completed", usage: { ...usage }, elapsedSeconds, archive, summary, evaluation, acceptance };
    } finally {
      await rm(tmp, { recursive: true, force: true });
    }
  }

  async removeUserContainer() {}

  async removeTaskContainer() {}
}
